#!/usr/bin/env node
"use strict";

// Generates src/text/uax14-data.js: the UAX #14 line-break class of every
// code point (as ranges) and the pair table, taken from the `linebreak`
// package (MIT, (c) Devon Govett) so the runtime line breaker needs no npm
// dependency, Node API or binary trie. The algorithm itself is ported in
// src/text/linebreak.js.
//
// node scripts/build-uax14-table.js

const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");

const root = path.resolve(__dirname, "..");
const packageDir = path.join(root, "node_modules", "linebreak");
const manifest = JSON.parse(fs.readFileSync(path.join(packageDir, "package.json"), "utf8"));
const entry = path.join(packageDir, "dist", "main.cjs");
const source = fs.readFileSync(entry, "utf8");

// The bundle keeps its trie and pair table module-private; re-export them.
const pairName = source.match(/const (\$[0-9a-f]+\$export\$5bdb8ccbf5c57afc) = \[/)[1];
const trieName = source.match(/const (\$[0-9a-f]+\$var\$classTrie) = /)[1];
const patched = `${source}\nmodule.exports.__internals = { pairs: ${pairName}, trie: ${trieName} };\n`;
const loaded = new Module(entry, module);
loaded.filename = entry;
loaded.paths = Module._nodeModulePaths(path.dirname(entry));
loaded._compile(patched, entry);
const { pairs, trie } = loaded.exports.__internals;

// Ranges as a flat array [start0, class0, start1, class1, ...]: code point
// `cp` has the class of the last start <= cp.
const ranges = [];
let previous = -1;
for (let cp = 0; cp <= 0x10ffff; cp++) {
  const value = trie.get(cp);
  if (value !== previous) {
    ranges.push(cp, value);
    previous = value;
  }
}

const data = {
  source: `linebreak@${manifest.version} (MIT)`,
  pairs,
  ranges
};
const body = `// Generated by scripts/build-uax14-table.js from ${data.source}. Do not edit.
(function (root, factory) {
  "use strict";
  const api = factory();
  if (typeof module === "object" && module && module.exports) module.exports = api;
  else {
    const namespace = root.RetainPdfRendering = root.RetainPdfRendering || {};
    namespace.Uax14Data = api;
  }
})(typeof this === "object" && this ? this : globalThis, function () {
  "use strict";

  return ${JSON.stringify(data)};
});
`;
const target = path.join(root, "src", "text", "uax14-data.js");
fs.writeFileSync(target, body);
console.log(`${path.relative(root, target)}: ${ranges.length / 2} ranges, ${(body.length / 1024).toFixed(1)} KB`);
